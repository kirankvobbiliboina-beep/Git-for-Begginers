def add_nums(a,b):
    """Return the sum of a and b"""
    return a + b

def divide_nums(a,b):
    """Return the divison of a and b"""
    return a / b

def sub_nums(a,b):
    """Return the subtraction of a and b"""
    return a - b

def power(a,b):
    """Return the exponential of a and b"""
    return a ** b

def mul_nums(a,b):
    """Return the multipication of a and b"""
    return a * b
